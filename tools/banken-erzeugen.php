<?php

/**
 * Development helper, not part of a release: writes app/data/banken.php,
 * the German banks by Bankleitzahl (name and BIC), from the npm package
 * "bankdata-germany" (license "MIT OR MPL-2.0", data of the Deutsche
 * Bundesbank). See docs/betrieb.md, "Bankdaten aktualisieren".
 *
 *   npm pack bankdata-germany@latest && tar -xzf bankdata-germany-*.tgz
 *   php tools/banken-erzeugen.php package
 *
 * The package is only read as data (dist/cjs/data/current.json and
 * next.json, package.json for the version) - nothing of it is executed.
 * next.json holds the changes that take effect on a later day; they are
 * applied when that day has come (or with --mit-naechsten).
 */

declare(strict_types=1);

if (PHP_SAPI !== 'cli') {
    exit(1);
}

$paket = rtrim($argv[1] ?? '', '/');
if ($paket === '' || !is_file($paket . '/package.json')) {
    fwrite(STDERR, "Usage: php tools/banken-erzeugen.php <unpacked package dir> [--mit-naechsten]\n");
    exit(2);
}
$mitNaechsten = in_array('--mit-naechsten', $argv, true);

$lies = static function (string $datei): array {
    $daten = json_decode((string) file_get_contents($datei), true, 16, JSON_THROW_ON_ERROR);
    if (!is_array($daten)) {
        throw new RuntimeException('Not a JSON object: ' . $datei);
    }

    return $daten;
};

$paketInfo = $lies($paket . '/package.json');
$banken = $lies($paket . '/dist/cjs/data/current.json');
$naechste = is_file($paket . '/dist/cjs/data/next.json') ? $lies($paket . '/dist/cjs/data/next.json') : [];

$stand = 'Paket ' . $paketInfo['version'];
if (isset($naechste['valid'])) {
    $ab = new DateTimeImmutable((string) $naechste['valid']);
    if ($mitNaechsten || $ab <= new DateTimeImmutable('now')) {
        $banken = array_replace($banken, $naechste['upsert'] ?? []);
        foreach ($naechste['remove'] ?? [] as $blz) {
            unset($banken[$blz]);
        }
        $stand .= ', gültig ab ' . $ab->format('d.m.Y');
    }
}

$zeilen = [];
ksort($banken, SORT_STRING);
foreach ($banken as $blz => $bank) {
    $blz = (string) $blz;
    $name = trim((string) ($bank[0] ?? ''));
    $bic = strtoupper(trim((string) ($bank[1] ?? '')));
    if (preg_match('/^[1-9]\d{7}$/D', $blz) !== 1 || $name === '') {
        throw new RuntimeException('Unexpected entry: ' . $blz);
    }
    if ($bic !== '' && preg_match('/^[A-Z]{4}DE[A-Z0-9]{2}([A-Z0-9]{3})?$/D', $bic) !== 1) {
        throw new RuntimeException('Unexpected BIC for ' . $blz);
    }
    $zeilen[] = '    ' . var_export($blz, true) . ' => [' . var_export($name, true) . ', '
        . ($bic === '' ? 'null' : var_export($bic, true)) . '],';
}

$kopf = <<<PHP
<?php

/*
 * German banks by Bankleitzahl: [name, BIC or null] (App\Support\Banken).
 * Generated by tools/banken-erzeugen.php - do not edit by hand.
 *
 * Source: npm package "bankdata-germany" by Markus Baumer, license
 * "MIT OR MPL-2.0" (used here under MIT); the data is the
 * Bankleitzahlendatei of the Deutsche Bundesbank.
 * Stand: {$stand}, erzeugt am %s, %d Bankleitzahlen.
 */

declare(strict_types=1);

return [

PHP;

$ziel = dirname(__DIR__) . '/app/data/banken.php';
file_put_contents($ziel, sprintf($kopf, date('d.m.Y'), count($zeilen)) . implode("\n", $zeilen) . "\n];\n");
fwrite(STDOUT, count($zeilen) . " banks written to app/data/banken.php ({$stand})\n");
